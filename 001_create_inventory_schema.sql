create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  email text,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  supplier_id bigint references public.suppliers(id) on delete set null,
  sku text not null unique,
  name text not null,
  unit text not null,
  minimum_stock integer not null default 0 check (minimum_stock >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  movement_type text not null check (movement_type in ('masuk', 'keluar')),
  quantity integer not null check (quantity > 0),
  transaction_date date not null default current_date,
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists products_category_id_idx on public.products(category_id);
create index if not exists products_supplier_id_idx on public.products(supplier_id);
create index if not exists stock_movements_product_id_idx on public.stock_movements(product_id);
create index if not exists stock_movements_transaction_date_idx on public.stock_movements(transaction_date);

alter table public.categories enable row level security;
alter table public.suppliers enable row level security;
alter table public.products enable row level security;
alter table public.stock_movements enable row level security;

create policy "Authenticated users can manage categories"
  on public.categories for all to authenticated
  using (true) with check (true);

create policy "Authenticated users can manage suppliers"
  on public.suppliers for all to authenticated
  using (true) with check (true);

create policy "Authenticated users can manage products"
  on public.products for all to authenticated
  using (true) with check (true);

create policy "Authenticated users can manage stock movements"
  on public.stock_movements for all to authenticated
  using (true) with check (true);
