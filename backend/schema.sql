create or replace function public.validate_transaction_refund()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  original_transaction public.transactions%rowtype;
  refunded_total numeric(14, 2);
begin
  if new.transaction_type = 'pendanaan' then
    if new.payment_type is not null or new.related_transaction_id is not null then
      raise exception 'Pendanaan tidak menggunakan jenis pembayaran pendapatan atau transaksi asal';
    end if;
  elsif new.transaction_type = 'pengeluaran' then
    if new.payment_type is not null or new.related_transaction_id is not null then
      raise exception 'Pengeluaran tidak menggunakan jenis pembayaran atau transaksi asal';
    end if;
  elsif new.transaction_type = 'pendapatan' and new.payment_type in ('dp', 'pelunasan') then
    if new.related_transaction_id is not null then
      raise exception 'Hanya refund yang dapat merujuk ke transaksi asal';
    end if;
  elsif new.transaction_type = 'pendapatan' and new.payment_type = 'refund' then
    select * into original_transaction
    from public.transactions
    where id = new.related_transaction_id
    for update;

    if not found
      or original_transaction.transaction_type <> 'pendapatan'
      or original_transaction.payment_type not in ('dp', 'pelunasan')
      or original_transaction.event_id <> new.event_id then
      raise exception 'Transaksi asal refund tidak valid untuk acara ini';
    end if;

    select coalesce(sum(amount), 0) into refunded_total
    from public.transactions
    where related_transaction_id = original_transaction.id
      and payment_type = 'refund'
      and id <> new.id;

    if refunded_total + new.amount > original_transaction.amount then
      raise exception 'Nominal refund melebihi sisa transaksi asal';
    end if;

  else
    raise exception 'Jenis transaksi tidak didukung';
  end if;

  return new;
end;
$$;

drop trigger if exists transactions_create_journals on public.transactions;
drop function if exists public.create_transaction_journals();
drop trigger if exists transactions_validate_refund on public.transactions;
create trigger transactions_validate_refund
  before insert or update on public.transactions
  for each row execute function public.validate_transaction_refund();

create or replace function public.keep_created_by_immutable()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.created_by is distinct from old.created_by then
    raise exception 'created_by tidak dapat diubah setelah record dibuat';
  end if;
  return new;
end;
$$;

